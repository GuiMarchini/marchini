const htmlLang = { pt: "pt-BR", en: "en" };

const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const finePointer = window.matchMedia("(hover: hover) and (pointer: fine)").matches;

function readStorage(key) {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}

function writeStorage(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch {
    /* storage unavailable */
  }
}

/* ---------- Language ---------- */

const main = document.getElementById("main");
const menuBtn = document.getElementById("menuBtn");
const mnav = document.getElementById("mnav");
let currentLang = "pt";

function applyLanguage(lang) {
  const dict = translations[lang];
  currentLang = lang;

  document.documentElement.lang = htmlLang[lang];

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const text = dict[el.dataset.i18n];
    if (text !== undefined) el.textContent = text;
  });

  document.querySelectorAll("[data-i18n-label]").forEach((el) => {
    const text = dict[el.dataset.i18nLabel];
    if (text !== undefined) el.setAttribute("aria-label", text);
  });

  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const text = dict[el.dataset.i18nTitle];
    if (text !== undefined) el.title = text;
  });

  document.querySelectorAll(".lang button").forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle("on", active);
    btn.setAttribute("aria-pressed", String(active));
  });

  updateMenuLabel();
  refreshIndicator();
}

function setLanguage(lang) {
  if (lang === currentLang) return;
  writeStorage("lang", lang);

  main.classList.add("switching");
  setTimeout(() => {
    applyLanguage(lang);
    main.classList.remove("switching");
  }, 160);
}

function initLanguage() {
  document.querySelectorAll(".lang button").forEach((btn) => {
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
  });

  const saved = readStorage("lang");
  if (saved && translations[saved] && saved !== "pt") applyLanguage(saved);
}

/* ---------- Navigation ---------- */

function updateMenuLabel() {
  const open = menuBtn.getAttribute("aria-expanded") === "true";
  menuBtn.setAttribute("aria-label", translations[currentLang][open ? "menuClose" : "menuOpen"]);
}

function setMenu(open) {
  menuBtn.setAttribute("aria-expanded", String(open));
  mnav.classList.toggle("open", open);
  mnav.inert = !open;
  updateMenuLabel();
}

function initMenu() {
  menuBtn.addEventListener("click", () => {
    setMenu(menuBtn.getAttribute("aria-expanded") !== "true");
  });

  mnav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => setMenu(false));
  });

  window.addEventListener("resize", () => {
    if (window.innerWidth > 1024) setMenu(false);
  });
}

let refreshIndicator = () => {};

function initScrollSpy() {
  const nav = document.querySelector(".nav-links");
  const indicator = nav.querySelector(".nav-ind");
  const links = [...nav.querySelectorAll("a[data-spy]")];
  const sections = links.map((link) => document.getElementById(link.dataset.spy));
  let activeId = null;
  let locked = false;
  let lockTimer;

  const moveIndicator = () => {
    const link = links.find((item) => item.dataset.spy === activeId);
    if (!link || link.offsetParent === null) return;

    const x = link.offsetLeft + link.offsetWidth / 2;

    if (!indicator.classList.contains("ready")) {
      indicator.style.transition = "none";
      indicator.style.transform = `translateX(${x}px)`;
      indicator.getBoundingClientRect();
      indicator.style.transition = "";
      indicator.classList.add("ready");
      return;
    }

    indicator.style.transform = `translateX(${x}px)`;
  };

  const setActive = (id) => {
    if (id === activeId) return;
    activeId = id;

    links.forEach((link) => {
      const active = link.dataset.spy === id;
      link.classList.toggle("on", active);
      if (active) link.setAttribute("aria-current", "true");
      else link.removeAttribute("aria-current");
    });

    moveIndicator();
  };

  const lockSpy = () => {
    locked = true;
    clearTimeout(lockTimer);
    lockTimer = setTimeout(() => (locked = false), 160);
  };

  links.forEach((link) => {
    link.addEventListener("click", () => {
      setActive(link.dataset.spy);
      lockSpy();
    });
  });

  window.addEventListener("scroll", () => locked && lockSpy(), { passive: true });

  const spy = new IntersectionObserver(
    (entries) => {
      if (locked) return;
      entries.forEach((entry) => entry.isIntersecting && setActive(entry.target.id));
    },
    { rootMargin: "-45% 0px -50% 0px" }
  );

  sections.forEach((section) => section && spy.observe(section));

  refreshIndicator = moveIndicator;
  window.addEventListener("resize", moveIndicator);
  document.fonts?.ready.then(moveIndicator);
}

function initProgress() {
  const bar = document.querySelector(".progress-bar");

  const update = () => {
    const max = document.documentElement.scrollHeight - window.innerHeight;
    const ratio = max > 0 ? window.scrollY / max : 0;
    bar.style.transform = `scaleX(${Math.min(ratio, 1)})`;
  };

  window.addEventListener("scroll", update, { passive: true });
  window.addEventListener("resize", update);
  update();
}

/* ---------- Scroll reveal ---------- */

function initReveal() {
  const items = document.querySelectorAll("[data-reveal]");

  if (reducedMotion || !("IntersectionObserver" in window)) {
    items.forEach((el) => el.classList.add("in"));
    return;
  }

  let lastY = window.scrollY;
  let goingUp = false;

  window.addEventListener(
    "scroll",
    () => {
      goingUp = window.scrollY < lastY;
      lastY = window.scrollY;
    },
    { passive: true }
  );

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        const el = entry.target;

        if (entry.isIntersecting) {
          el.classList.toggle("fast", goingUp);
          el.classList.add("in");
        } else {
          el.classList.remove("in");
        }
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -6% 0px" }
  );

  items.forEach((el) => observer.observe(el));
}

/* ---------- Pointer effects ---------- */

function initGlow() {
  document.addEventListener("pointermove", (event) => {
    const target = event.target.closest?.(".glow");
    if (!target) return;

    const rect = target.getBoundingClientRect();
    target.style.setProperty("--mx", `${event.clientX - rect.left}px`);
    target.style.setProperty("--my", `${event.clientY - rect.top}px`);
  });
}

function initCursorGlow() {
  if (!finePointer || reducedMotion) return;

  const glow = document.querySelector(".cursor-glow");
  let x = 0;
  let y = 0;
  let queued = false;

  window.addEventListener("pointermove", (event) => {
    x = event.clientX;
    y = event.clientY;
    glow.classList.add("on");

    if (queued) return;
    queued = true;
    requestAnimationFrame(() => {
      glow.style.transform = `translate(${x}px, ${y}px)`;
      queued = false;
    });
  });

  document.addEventListener("pointerleave", () => glow.classList.remove("on"));
}

function initCursorTip() {
  if (!finePointer) return;

  const tip = document.querySelector(".cursor-tip");
  const label = tip.querySelector("span");
  let x = 0;
  let y = 0;
  let queued = false;

  const place = () => {
    tip.style.transform = `translate(calc(${x}px - 50%), calc(${y}px - 50%))`;
    queued = false;
  };

  const track = (event) => {
    x = event.clientX;
    y = event.clientY;
    if (queued) return;
    queued = true;
    requestAnimationFrame(place);
  };

  document.addEventListener("pointermove", track);

  document.addEventListener("pointerover", (event) => {
    const target = event.target.closest("[data-cursor]");
    if (target) {
      track(event);
      label.textContent = translations[currentLang][target.dataset.cursor];
      tip.dataset.mode = target.dataset.cursor;
    }
    tip.classList.toggle("on", Boolean(target));
  });

  document.addEventListener("pointerleave", () => tip.classList.remove("on"));
}

